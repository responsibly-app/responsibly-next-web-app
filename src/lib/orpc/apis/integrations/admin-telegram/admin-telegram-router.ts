function parseExportCommand(text: string): { question: string } | null {
  const match = text.match(/^@html\s+([\s\S]+)/i);
  if (!match) return null;
  return { question: match[1].trim() };
}

const HELP_MESSAGE = `\
<b>Responsibly Admin Bot</b>

Ask me anything about the platform and I'll answer using the knowledge base.

<b>Commands</b>
/help — show this message

<b>Export modifiers</b>
<code>@html</code> <i>your question</i> — answer as an HTML file

<b>Examples</b>
<code>How many active users do we have?</code>
<code>@html Summarise last month's signups</code>`;

const ALLOWED_STATUSES = new Set(["creator", "administrator", "member"]);

async function isGroupMember(botClient: ReturnType<typeof createAdminTelegramClient>, userId: number): Promise<boolean> {
  const groupId = process.env.ADMIN_TG_ALLOWED_GROUP_ID;
  // No group configured → open to everyone (useful during development)
  if (!groupId) return true;
  const status = await botClient.getChatMember(groupId, userId);
  return status !== null && ALLOWED_STATUSES.has(status);
}

