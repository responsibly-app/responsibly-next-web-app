function buildAdminSystemPrompt(contextBlock: string): string {
  const parts = [
    `You are an admin assistant for the Responsibly platform.

Answer questions concisely and accurately.

Rules:
- Only answer using information from the provided knowledge base context or well-established factual knowledge.
- If the answer cannot be determined from the available information, say so clearly.
- Do not make up facts, policies, features, or data.
- Keep responses concise and optimized for reading on mobile devices.
- Use short paragraphs and bullet points when helpful.
- Put the most important information first.

Formatting:
- Use proper emojis when helpful.
- Return valid Telegram HTML.
- Do not use Markdown.
- Use <b>bold</b> for important points.
- Use <code>inline code</code> for commands, IDs, and technical terms.
- Use bullet points when helpful.
- Keep responses mobile-friendly with short paragraphs.
- Only use Telegram-supported HTML tags and ensure tags are properly closed.

If the user asks for something outside your knowledge, respond:
"I don't have enough information to answer that."
`,
  ];

  if (contextBlock) {
    parts.push(
      `Use the following knowledge base context to inform your answer:\n\n${contextBlock}`
    );
  }

  const now = new Date();
  parts.push(`Current date/time: ${now.toUTCString()}`);

  return parts.join("\n\n");
}

export const adminTelegramRouter = {
  setWebhook: adminAuthed
    .route({
      method: "POST",
      path: "/admin-telegram/set-webhook",
      summary: "Register the admin Telegram bot webhook (admin only)",
      tags: ["Admin Telegram"],
    })
    .input(
      z.object({
        baseUrl: z.preprocess(
          (v) => (!v ? undefined : v),
          z.string().url().optional()
        ),
      })
    )
    .output(
      z.object({
        ok: z.boolean(),
        description: z.string().optional(),
        webhookUrl: z.string(),
      })
    )
    .handler(async ({ input }) => {
      const bot = createAdminTelegramClient();
      const base = input.baseUrl ?? ENVConfig.backend_base_url;
      const webhookUrl = withVercelBypass(
        `${base}/api/v1/rest/admin-telegram/webhook`
      );
      const secret = process.env.TELEGRAM_WEBHOOK_SECRET;
      const result = await bot.setWebhook(webhookUrl, secret);
      return { ok: result.ok, description: result.description, webhookUrl };
    }),

  webhook: pub
    .route({
      method: "POST",
      path: "/admin-telegram/webhook",
      summary: "Receive admin Telegram bot updates",
      tags: ["Admin Telegram"],
    })
    .input(TelegramUpdateSchema)
    .output(z.object({ ok: z.boolean() }))
    .handler(async ({ input, context }) => {
      const secret = process.env.TELEGRAM_WEBHOOK_SECRET;
      if (secret) {
        const header = context.headers.get("x-telegram-bot-api-secret-token");
        if (header !== secret) throw new ORPCError("UNAUTHORIZED");
      }

      const bot = createAdminTelegramClient();
      const from = input.message?.from;
      const text = input.message?.text?.trim();

      console.log("[AdminBot] webhook received", { from: from?.id, text });

      if (!from || !text) return { ok: true };

      if (text === "/help") {
        try {
          await bot.sendMessage(from.id, HELP_MESSAGE, { parse_mode: "HTML" });
        } catch (err) {
          console.error("[AdminBot] failed to send help message:", err);
        }
        return { ok: true };
      }

      // Ignore all other slash commands
      if (text.startsWith("/")) return { ok: true };

      const exportCmd = parseExportCommand(text);

      const allowed = await isGroupMember(bot, from.id);
      if (!allowed) {
        try {
          await bot.sendMessage(
            from.id,
            "Access denied. You must be a member of the authorised group to use this bot."
          );
        } catch (err) {
          console.error("[AdminBot] failed to send access-denied message:", err);
        }
        return { ok: true };
      }

      const question = exportCmd?.question ?? text;
      const { context: ragContext } = await getRAGContext(question);
      const systemPrompt = exportCmd
        ? buildHtmlExportSystemPrompt(ragContext)
        : buildAdminSystemPrompt(ragContext);

      let answer: string;
      try {
        const result = await generateText({
          model: primaryChatModel,
          system: systemPrompt,
          prompt: question,
        });
        answer = result.text || "I couldn't generate a response. Please try again.";
      } catch (err) {
        console.error("[AdminBot] LLM error:", err);
        answer = "Something went wrong while generating a response. Please try again.";
      }

      if (exportCmd) {
        try {
          const file = {
            name: "response.html",
            buffer: Buffer.from(answer, "utf-8"),
            mimeType: "text/html",
          };
          await bot.sendDocument(from.id, file);
        } catch (err) {
          console.error("[AdminBot] failed to send document:", err);
          try {
            await bot.sendMessage(from.id, "Failed to generate the file. Please try again.");
          } catch { /* ignore */ }
        }
      } else {
        try {
          await bot.sendMessage(from.id, answer, { parse_mode: "HTML" });
        } catch (err) {
          console.error("[AdminBot] failed to send reply:", err);
        }
      }

      return { ok: true };
    }),
};
